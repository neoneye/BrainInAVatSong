# align.py: match the whisper word timestamps (docs/timing/whisper_words.json) to the lyric sheet and write
# video/src/lyrics.js. Run: python3 tools/align.py
import json, re, difflib
words = json.load(open('docs/timing/whisper_words.json'))
norm = lambda w: re.sub(r"[^a-z0-9]", "", w.lower().replace("’", "'").replace("'", ""))
# section tag → (section name, subtitle format, who sings). Who is a guess: verses her, rap him, chorus both.
SEC = [('Intro build', None), ('Whispered', None), ('Verse 1', ('Verse 1', 'label', 'her')), ('Pre-chorus', ('Pre-chorus', 'note', 'her')),
       ('Chorus', ('Chorus', 'karaoke', 'both')), ('Final chorus', ('Final Chorus', 'karaoke', 'both')), ('Reverb', ('Echo', 'fog', 'her')),
       ('Verse 2', ('Verse 2', 'label', 'her')), ('Rap', ('Rap', 'term', 'him')), ('Bridge', ('Bridge', 'caption', 'her')),
       ('Pause', ('Pause', 'caption', 'her')), ('Drums build', ('Build', 'note', 'her'))]
lines, cur, seen_whisper = [], ('Intro', 'fog', 'her'), 0
for raw in open('assets/lyrics.txt').read().split('\n'):
    raw = raw.strip()
    if not raw: continue
    m = re.match(r"\[(.*?)\]", raw)
    if m:
        tag = m.group(1)
        if tag.startswith('Whispered'):
            seen_whisper += 1
            cur = (['Intro', 'Whisper', 'Whisper', 'Outro'][min(seen_whisper - 1, 3)], 'fog', 'her')
        else:
            for k, v in SEC:
                if tag.startswith(k) and v: cur = v
        continue
    lines.append({'sec': cur[0], 'fmt': cur[1], 'who': cur[2], 'text': raw})
    if cur[0] in ('Echo',) or (cur[0] == 'Final Chorus' and raw.startswith('Leave me')):  # the echo repeats twice more in the recording
        for _ in range(1 if cur[0] == 'Echo' else 2): lines.append({'sec': 'Echo', 'fmt': 'fog', 'who': 'her', 'text': 'Wanting more…'})
for L in lines[-2:]: L['sec'] = 'Outro'
lw = [(i, w) for i, L in enumerate(lines) for w in L['text'].split()]
a, b = [norm(w) for _, w in lw], [norm(w[0]) for w in words]
times = [None] * len(lw)
for blk in difflib.SequenceMatcher(None, a, b, autojunk=False).get_matching_blocks():
    for k in range(blk.size): times[blk.a + k] = (words[blk.b + k][1], words[blk.b + k][2])
# fill unmatched words by interpolating between matched neighbours
known = [i for i, t in enumerate(times) if t]
for i in range(len(times)):
    if times[i]: continue
    p = max([k for k in known if k < i], default=None); n = min([k for k in known if k > i], default=None)
    if p is None: t0 = times[n][0] - 0.4 * (n - i); times[i] = (t0, t0 + 0.35)
    elif n is None: t0 = times[p][1] + 0.4 * (i - p - 1); times[i] = (t0, t0 + 0.35)
    else:
        g0, g1 = times[p][1], times[n][0]; g1 = min(g1, g0 + 0.6 * (n - p))
        step = (g1 - g0) / (n - p); t0 = g0 + step * (i - p - 1); times[i] = (round(t0, 2), round(t0 + step * 0.9, 2))
    print('interpolated:', lw[i][1], times[i], 'line', lines[lw[i][0]]['text'][:40])
out = []
for i, L in enumerate(lines):
    ws = [[w, max(0, round(times[k][0], 2)), round(max(times[k][1], times[k][0] + 0.12), 2)] for k, (li, w) in enumerate(lw) if li == i]
    for j in range(len(ws) - 1): ws[j][2] = min(ws[j][2], max(ws[j][1] + 0.1, ws[j + 1][1]))
    out.append({'sec': L['sec'], 'fmt': L['fmt'], 'who': L['who'], 't0': ws[0][1], 't1': ws[-1][2], 'words': ws})
with open('video/src/lyrics.js', 'w') as f:
    f.write("// lyrics.js: generated by tools/align.py from assets/lyrics.txt, aligned to assets/song.mp3 with faster-whisper word timestamps.\n"
            "// Each line: { sec, fmt (subtitle format), who (her | him | both: a guess, edit freely), t0, t1, words: [[word, t0, t1], ...] }\n"
            "export const LYRICS = [\n" + ",\n".join("  " + json.dumps(L, ensure_ascii=False) for L in out) + "\n];\n")
for L in out: print(f"{L['t0']:7.2f} {L['t1']:7.2f} {L['sec']:13s} {L['fmt']:8s} {' '.join(w[0] for w in L['words'])}")
