// analyze.mjs: loudness envelope, onset strength and beat grid of assets/song.mp3 → video/src/audio.js
//   node tools/analyze.mjs
import { spawnSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
const SR = 22050, FPS = 30;
const r = spawnSync('ffmpeg', ['-v', 'error', '-i', 'assets/song.mp3', '-ac', '1', '-ar', String(SR), '-f', 'f32le', '-'], { maxBuffer: 1 << 30 });
const pcm = new Float32Array(r.stdout.buffer, r.stdout.byteOffset, r.stdout.length >> 2), DUR = pcm.length / SR;
// envelope at 200 Hz, full band and low band (one-pole low-pass ~150 Hz for the kick)
const HOP = Math.round(SR / 200), EF = SR / HOP, n = Math.floor(pcm.length / HOP);
const env = new Float32Array(n), low = new Float32Array(n);
let lp = 0; const a = 1 - Math.exp(-2 * Math.PI * 150 / SR);
for (let i = 0; i < n; i++) { let s = 0, l = 0; for (let k = 0; k < HOP; k++) { const x = pcm[i * HOP + k]; lp += a * (x - lp); s += x * x; l += lp * lp; } env[i] = Math.sqrt(s / HOP); low[i] = Math.sqrt(l / HOP); }
const flux = new Float32Array(n);
for (let i = 2; i < n; i++) flux[i] = Math.max(0, Math.log(1e-4 + low[i]) - Math.log(1e-4 + low[i - 2])) + 0.5 * Math.max(0, Math.log(1e-4 + env[i]) - Math.log(1e-4 + env[i - 2]));
// beat: best period near 140 BPM and phase by comb score on the onset flux
let best = [0, 0, 0];
for (let bpm = 136; bpm <= 144; bpm += 0.01) {
  const per = 60 / bpm * EF;
  for (let ph = 0; ph < per; ph += 1) { let s = 0; for (let x = ph; x < n; x += per) s += flux[Math.round(x)] || 0; if (s > best[0]) best = [s, bpm, ph / EF]; }
}
const BEAT = 60 / best[1], BEAT0 = best[2];
const mx = arr => { const s = [...arr].sort((p, q) => p - q); return s[Math.floor(s.length * 0.995)]; };
const em = mx(env), fm = mx(flux), N = Math.ceil(DUR * FPS) + 2, RMS = [], ONSET = [];
for (let f = 0; f < N; f++) {
  const i0 = Math.floor(f / FPS * EF), i1 = Math.floor((f + 1) / FPS * EF); let e = 0, o = 0, c = 0;
  for (let i = i0; i < i1 && i < n; i++) { e += env[i]; o = Math.max(o, flux[i]); c++; }
  RMS.push(+(c ? Math.min(1, e / c / em) : 0).toFixed(2)); ONSET.push(+Math.min(1.5, o / fm).toFixed(2));
}
writeFileSync('video/src/audio.js', `// audio.js: generated by tools/analyze.mjs: loudness envelope and onset strength at ${FPS} fps, plus the beat grid.
export const BEAT = ${BEAT.toFixed(5)}, BEAT0 = ${BEAT0.toFixed(4)}, DUR = ${DUR.toFixed(2)}, FPS_DATA = ${FPS};
export const RMS = [${RMS.join(', ')}];
export const ONSET = [${ONSET.join(', ')}];
`);
console.log('bpm', best[1].toFixed(2), 'beat0', BEAT0.toFixed(3), 'dur', DUR.toFixed(2));
// coarse energy map, 4 s buckets, for the timeline author
let line = ''; for (let t = 0; t < DUR; t += 4) { let s = 0; for (let f = t * FPS; f < (t + 4) * FPS && f < N; f++) s += RMS[f]; line += `${t}:${(s / 120).toFixed(2)} `; } console.log(line);
